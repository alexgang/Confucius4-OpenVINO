        assert new.startswith(old.rstrip('\n')), '当日日志不是纯追加'
        assert new.count('### 第 ') == old.count('### 第 ') + 1, '轮次增量不对'
        write_atomic(LOG_MD, new)
        out.append('当日日志：%d → %d B（append-only）'
                   % (len(old.encode('utf-8')), len(new.encode('utf-8'))))

