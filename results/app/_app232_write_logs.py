def read(p):
    if not os.path.isfile(p):
        return None
    with io.open(p, 'r', encoding='utf-8', newline='') as f:
        return f.read()


def write_atomic(p, text):
    tmp = p + '.tmp_app232'
    with io.open(tmp, 'w', encoding='utf-8', newline='') as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    assert os.path.getsize(tmp) > 0, '临时文件 0 B'
    os.replace(tmp, p)


